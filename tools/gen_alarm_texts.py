"""Generate custom_components/danfoss_link/alarm_texts.py from the app's string resources.

    python3 tools/gen_alarm_texts.py <decoded-apk>/res

The CC reports alarms as Android string resource names (titleTextId,
descriptionTextId); the app looks them up in res/values*/strings.xml.
"""

from __future__ import annotations

import pathlib
import pprint
import re
import sys
import xml.etree.ElementTree as ET

PATTERN = re.compile(r"^IDS_UA[12]_ALERTVIEWER_")
OUT = pathlib.Path(__file__).parents[1] / "custom_components" / "danfoss_link" / "alarm_texts.py"


def _unescape(text: str) -> str:
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] == '"':
        text = text[1:-1]
    return (
        text.replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"').replace("\\\\", "\\")
    )


def main(res: pathlib.Path) -> None:
    texts: dict[str, dict[str, str]] = {}
    for values in sorted(res.glob("values*")):
        strings = values / "strings.xml"
        if not strings.exists():
            continue
        lang = "en" if values.name == "values" else values.name.removeprefix("values-")
        if not re.fullmatch(r"[a-z]{2}", lang):
            continue
        found = {
            el.get("name"): _unescape("".join(el.itertext()))
            for el in ET.parse(strings).getroot().iter("string")
            if PATTERN.match(el.get("name", "")) and not el.get("name", "").endswith("_HELP")
        }
        if found:
            texts[lang] = dict(sorted(found.items()))
    body = pprint.pformat(texts, width=100, sort_dicts=False)
    OUT.write_text(
        '"""Alarm texts from the Danfoss Link app 1.3.1 (generated by tools/gen_alarm_texts.py).\n\n'
        "The CC reports alarms as Android string resource names (titleTextId,\n"
        'descriptionTextId); these are the app\'s translations of them.\n"""\n\n'
        f"ALARM_TEXTS: dict[str, dict[str, str]] = {body}\n"
    )
    print(f"wrote {OUT} ({', '.join(texts)})")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]))
